// TestScanPreservesCreatedAndSlugOnUpdate guards the regression where re-running
// hero scan flipped an existing entry's authored created: to today and dropped
// its slug: (undoing the created-date backfill on every scan). On MergeUpdate the
// authored created:/slug: must be carried forward, and the write must be
// idempotent across repeated scans. Fresh MergeCreate entries must still get
// today's created: and an emitted slug:.
func TestScanPreservesCreatedAndSlugOnUpdate(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "knowledge", "rules", "ci-github-actions", "spec.md")
	os.MkdirAll(filepath.Dir(path), 0o755)

	// (1) Existing auto-generated, uncustomized entry with authored provenance.
	existing := `---
title: CI Must Pass (GitHub Actions)
type: rule
slug: ci-github-actions
status: active
created: 2020-01-01
scope: ["*"]
tags: [auto-generated, project-scan, ci]
---
# CI Must Pass (GitHub Actions)

Auto-generated by ` + "`hero scan`" + `. Review and adjust.

## Exceptions

<!-- Under what circumstances can CI failures be bypassed? Who approves? -->
`
	if err := os.WriteFile(path, []byte(existing), 0o644); err != nil {
		t.Fatalf("write existing: %v", err)
	}

	// (2) Freshly generated content for the same slug/path — today's created:,
	// and (per the bug) no slug: line at all.
	today := time.Now().Format("2006-01-02")
	freshContent := `---
title: CI Must Pass (GitHub Actions)
type: rule
status: active
created: ` + today + `
scope: ["*"]
tags: [auto-generated, project-scan, ci]
---
# CI Must Pass (GitHub Actions)

Auto-generated by ` + "`hero scan`" + `. Review and adjust.

## Exceptions

<!-- Under what circumstances can CI failures be bypassed? Who approves? -->
`
	entry := GeneratedEntry{
		Type:    "rule",
		Slug:    "ci-github-actions",
		Path:    path,
		Content: freshContent,
	}

	// (3) Plan → assert MergeUpdate → execute.
	decisions := PlanMerge([]GeneratedEntry{entry}, false)
	if len(decisions) != 1 || decisions[0].Strategy != MergeUpdate {
		t.Fatalf("strategy = %v, want MergeUpdate", decisions[0].Strategy)
	}
	if _, err := ExecuteMerge(decisions); err != nil {
		t.Fatalf("ExecuteMerge: %v", err)
	}

	// (4) Authored created:/slug: preserved after the first scan.
	assertField(t, path, "created", "2020-01-01")
	assertField(t, path, "slug", "ci-github-actions")

	// (5) Scan a second time — still unchanged (idempotency).
	decisions = PlanMerge([]GeneratedEntry{entry}, false)
	if decisions[0].Strategy != MergeUpdate {
		t.Fatalf("second scan strategy = %v, want MergeUpdate", decisions[0].Strategy)
	}
	if _, err := ExecuteMerge(decisions); err != nil {
		t.Fatalf("second ExecuteMerge: %v", err)
	}
	assertField(t, path, "created", "2020-01-01")
	assertField(t, path, "slug", "ci-github-actions")

	// (6) MergeCreate still stamps today's created: and emits a slug: — the
	// preservation logic must not leak into fresh creation.
	newPath := filepath.Join(dir, "knowledge", "rules", "ci-fresh", "spec.md")
	newEntry := GeneratedEntry{
		Type: "rule",
		Slug: "ci-fresh",
		Path: newPath,
		Content: `---
title: CI Fresh
type: rule
status: active
created: ` + today + `
tags: [auto-generated, project-scan, ci]
---
# CI Fresh
`,
	}
	createDecisions := PlanMerge([]GeneratedEntry{newEntry}, false)
	if createDecisions[0].Strategy != MergeCreate {
		t.Fatalf("new entry strategy = %v, want MergeCreate", createDecisions[0].Strategy)
	}
	if _, err := ExecuteMerge(createDecisions); err != nil {
		t.Fatalf("create ExecuteMerge: %v", err)
	}
	assertField(t, newPath, "created", today)
	assertField(t, newPath, "slug", "ci-fresh")
}

// assertField reads content back from disk and asserts a top-level frontmatter
// scalar equals want.
func assertField(t *testing.T, path, key, want string) {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read back %s: %v", path, err)
	}
	got := frontmatterValue(string(data), key)
	if got != want {
		t.Errorf("%s: %s = %q, want %q\n---\n%s", filepath.Base(filepath.Dir(path)), key, got, want, string(data))
	}
	if key == "slug" && !strings.Contains(string(data), "slug: "+want) {
		t.Errorf("%s: expected literal `slug: %s` line, content:\n%s", path, want, string(data))
	}
}

func TestExecuteMerge(t *testing.T) {
	dir := t.TempDir()

	decisions := []MergeDecision{
		{
			Entry:    GeneratedEntry{Slug: "new", Path: filepath.Join(dir, "new", "spec.md"), Content: "new content"},
			Strategy: MergeCreate,
		},
		{
			Entry:    GeneratedEntry{Slug: "updated", Path: filepath.Join(dir, "updated", "spec.md"), Content: "updated content"},
			Strategy: MergeUpdate,
		},
		{
			Entry:    GeneratedEntry{Slug: "skipped", Path: filepath.Join(dir, "skipped", "spec.md"), Content: "skip"},
			Strategy: MergeSkipCustomized,
		},
	}

	result, err := ExecuteMerge(decisions)
	if err != nil {
		t.Fatalf("ExecuteMerge: %v", err)
	}

	if result.Created != 1 {
		t.Errorf("Created = %d, want 1", result.Created)
	}
	if result.Updated != 1 {
		t.Errorf("Updated = %d, want 1", result.Updated)
	}
	if result.Skipped != 1 {
		t.Errorf("Skipped = %d, want 1", result.Skipped)
	}

	// Verify files
	data, err := os.ReadFile(filepath.Join(dir, "new", "spec.md"))
	if err != nil {
		t.Fatalf("new entry not created: %v", err)
	}
	if string(data) != "new content" {
		t.Error("new entry content wrong")
	}

	data, err = os.ReadFile(filepath.Join(dir, "updated", "spec.md"))
	if err != nil {
		t.Fatalf("updated entry not created: %v", err)
	}
	if string(data) != "updated content" {
		t.Error("updated entry content wrong")
	}

	// Skipped entry should NOT exist
	if _, err := os.Stat(filepath.Join(dir, "skipped", "spec.md")); err == nil {
		t.Error("skipped entry should not have been written")
	}
}
