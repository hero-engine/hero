func TestPlanMerge(t *testing.T) {
	dir := t.TempDir()

	// Create one existing auto-generated entry
	existingPath := filepath.Join(dir, "existing", "spec.md")
	os.MkdirAll(filepath.Dir(existingPath), 0o755)
	os.WriteFile(existingPath, []byte(`---
tags: [auto-generated, project-scan]
---
Old content
<!-- Add details -->
`), 0o644)

	// Create one existing customized entry
	customPath := filepath.Join(dir, "custom", "spec.md")
	os.MkdirAll(filepath.Dir(customPath), 0o755)
	os.WriteFile(customPath, []byte(`---
tags: [user-modified]
---
Custom content the user wrote
`), 0o644)

	entries := []GeneratedEntry{
		{Slug: "new-entry", Path: filepath.Join(dir, "new", "spec.md"), Content: "new"},
		{Slug: "existing", Path: existingPath, Content: "updated"},
		{Slug: "custom", Path: customPath, Content: "would overwrite"},
	}

	decisions := PlanMerge(entries, false)

	if len(decisions) != 3 {
		t.Fatalf("expected 3 decisions, got %d", len(decisions))
	}

	strategies := map[string]MergeStrategy{}
	for _, d := range decisions {
		strategies[d.Entry.Slug] = d.Strategy
	}

	if strategies["new-entry"] != MergeCreate {
		t.Errorf("new-entry: got %v, want MergeCreate", strategies["new-entry"])
	}
	if strategies["existing"] != MergeUpdate {
		t.Errorf("existing: got %v, want MergeUpdate", strategies["existing"])
	}
	if strategies["custom"] != MergeSkipCustomized {
		t.Errorf("custom: got %v, want MergeSkipCustomized", strategies["custom"])
	}
}

