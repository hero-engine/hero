// slugify converts a name to a kebab-case slug.
func slugify(name string) string {
	s := strings.ToLower(name)
	s = strings.ReplaceAll(s, " ", "-")
	s = strings.ReplaceAll(s, "(", "")
	s = strings.ReplaceAll(s, ")", "")
	s = strings.ReplaceAll(s, ".", "")
	s = strings.ReplaceAll(s, "/", "-")

	// Collapse multiple hyphens
	for strings.Contains(s, "--") {
		s = strings.ReplaceAll(s, "--", "-")
	}
	s = strings.TrimRight(s, "-")
	return s
}

// langGlob returns a file glob pattern for a language.
func langGlob(lang string) string {
	switch lang {
	case "Go":
		return "*.go"
	case "JavaScript":
		return "*.{js,jsx,mjs,cjs}"
	case "TypeScript":
		return "*.{ts,tsx,mts}"
	case "Python":
		return "*.py"
	case "Ruby":
		return "*.rb"
	case "Rust":
		return "*.rs"
	case "Java":
		return "*.java"
	case "PHP":
		return "*.php"
	default:
		return "*"
	}
}

// langOrAll returns the language name or "all" if empty.
func langOrAll(lang string) string {
	if lang == "" {
		return "all"
	}
	return lang
}
