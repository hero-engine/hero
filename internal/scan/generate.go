package scan

import (
	"fmt"
	"path/filepath"
	"strings"
	"time"
)

// GeneratedEntry represents a knowledge base entry to be created.
type GeneratedEntry struct {
	Type    string // context, convention, rule
	Slug    string
	Path    string // absolute path to spec.md
	Content string // full spec content
}

// Generate creates knowledge base entries from a scan Result.
// heroDir is the absolute path to the .hero directory.
// It performs a deep enrichment pass (reading source files) to produce a richer
// project overview than static marker detection alone can provide.
func Generate(r *Result, heroDir string) []GeneratedEntry {
	var entries []GeneratedEntry
	date := time.Now().Format("2006-01-02")

	// 1. Deep enrichment pass — reads README, go.mod, package.json, source files
	e := Enrich(r.ProjectRoot, r)

	// 2. Rich project overview context entry (uses enrichment)
	overviewEntry := GenerateRichProjectOverview(r, e, heroDir, date)

	// 3. Import existing knowledge from AGENTS.md, .opencode/instructions, etc.
	var importResult *ImportResult
	if len(r.ImportSources) > 0 {
		var allSections []ImportedSection
		for _, src := range r.ImportSources {
			allSections = append(allSections, ParseImportSource(src)...)
		}
		importResult = ClassifyImportedSections(allSections)
		importResult.Sources = r.ImportSources

		// Enrich the project overview with imported tech stack + architecture info
		overviewEntry.Content = EnrichOverviewFromImport(overviewEntry.Content, importResult)
	}

	entries = append(entries, overviewEntry)

	// 4. Generate entries from imported knowledge (architecture, conventions, rules, commands, modules)
	if importResult != nil {
		imported := ImportToEntries(importResult, heroDir, date)
		entries = append(entries, imported...)
	}

	// 5. Generate multi-module context entry if applicable
	if r.MultiModule != nil && len(r.MultiModule.Subprojects) > 0 {
		entry := generateMultiModuleEntry(r.MultiModule, r.FrameworkDetails, heroDir, date)
		entries = append(entries, entry)
	}

	// 6. Convention stubs for detected linters/formatters
	entries = append(entries, generateLinterConventions(r, heroDir, date)...)

	// 7. Rule stubs for CI enforcement
	entries = append(entries, generateCIRules(r, heroDir, date)...)

	// 8. Convention for detected test frameworks
	entries = append(entries, generateTestConventions(r, heroDir, date)...)

	return entries
}


func generateLinterConventions(r *Result, heroDir, date string) []GeneratedEntry {
	var entries []GeneratedEntry

	for _, l := range r.Linters {
		slug := "use-" + slugify(l.Name)
		path := filepath.Join(heroDir, "knowledge", "conventions", slug, "spec.md")

		langScope := "*"
		if l.Language != "" {
			langScope = langGlob(l.Language)
		}

		content := fmt.Sprintf(`---
title: Use %s
type: convention
status: draft
created: %s
scope: ["%s"]
tags: [auto-generated, project-scan, linting]
---
# Use %s

Auto-generated by `+"`hero scan`"+`. Review and adjust.

## Rule

All %s code must pass **%s** checks. Configuration is in `+"`%s`"+`.

## Rationale

Consistent code style and catching common errors early via static analysis.

## Enforcement

<!-- Describe how this is enforced: pre-commit hook, CI check, editor integration, etc. -->

## Exceptions

<!-- When is it acceptable to disable or override a rule? -->
`, l.Name, date, langScope, l.Name, langOrAll(l.Language), l.Name, l.ConfigFile)

		entries = append(entries, GeneratedEntry{
			Type:    "convention",
			Slug:    slug,
			Path:    path,
			Content: content,
		})
	}

	return entries
}

