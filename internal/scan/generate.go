func generateMultiModuleEntry(mm *MultiModuleInfo, fwDetails []FrameworkDetail, heroDir, date string) GeneratedEntry {
	slug := "multi-module-structure"
	path := filepath.Join(heroDir, "knowledge", "context", slug, "spec.md")

	var sb strings.Builder

	sb.WriteString("---\n")
	sb.WriteString("title: Multi-Module Project Structure\n")
	sb.WriteString("type: context\n")
	sb.WriteString("status: active\n")
	sb.WriteString(fmt.Sprintf("created: %s\n", date))
	sb.WriteString("tags: [auto-generated, project-scan, multi-module]\n")
	sb.WriteString("---\n\n")

	sb.WriteString(fmt.Sprintf("## Build System: %s\n\n", mm.BuildSystem))
	sb.WriteString(fmt.Sprintf("Root configuration: `%s`\n\n", mm.RootConfig))

	sb.WriteString(fmt.Sprintf("## Subprojects (%d)\n\n", len(mm.Subprojects)))
	sb.WriteString("| Module | Directory | Language | Kind |\n")
	sb.WriteString("|--------|-----------|----------|------|\n")
	for _, sp := range mm.Subprojects {
		lang := sp.Language
		if lang == "" {
			lang = "-"
		}
		kind := sp.Kind
		if kind == "" {
			kind = "-"
		}
		sb.WriteString(fmt.Sprintf("| %s | `%s` | %s | %s |\n", sp.Name, sp.Dir, lang, kind))
	}
	sb.WriteString("\n")

	// Add framework details if present
	if len(fwDetails) > 0 {
		sb.WriteString("## Framework Details\n\n")
		for _, fd := range fwDetails {
			sb.WriteString(fmt.Sprintf("### %s", fd.Name))
			if fd.Version != "" {
				sb.WriteString(fmt.Sprintf(" %s", fd.Version))
			}
			sb.WriteString("\n\n")
			if len(fd.Directories) > 0 {
				sb.WriteString("Modules using this framework:\n")
				for _, d := range fd.Directories {
					sb.WriteString(fmt.Sprintf("- `%s`\n", d))
				}
				sb.WriteString("\n")
			}
			if len(fd.Conventions) > 0 {
				sb.WriteString("Detected structure conventions: ")
				sb.WriteString(strings.Join(fd.Conventions, ", "))
				sb.WriteString("\n\n")
			}
		}
	}

	sb.WriteString("<!-- Add dependency relationships, build order, and deployment information -->\n")

	return GeneratedEntry{
		Type:    "context",
		Slug:    slug,
		Path:    path,
		Content: sb.String(),
	}
}

