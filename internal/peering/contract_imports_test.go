// writePeerManifestWithContracts puts a peer-manifest.yaml under the
// given workspace's .hero/, listing one Go-symbol contract entry.
// Returns the manifest path.
func writePeerManifestWithContracts(t *testing.T, root, peerID, pkg, name, conv string) string {
	t.Helper()
	heroDir := filepath.Join(root, ".hero")
	if err := os.MkdirAll(heroDir, 0o755); err != nil {
		t.Fatalf("mkdir hero: %v", err)
	}
	m := contractpeering.PeerManifest{
		Schema:           1,
		ContractsVersion: contractpeering.PeeringContractsVersion,
		Repo: contractpeering.RepoIdentity{
			PeerID: peerID,
			Name:   filepath.Base(root),
		},
		GeneratedAt: time.Now().UTC(),
		Contracts: &contractpeering.ContractsSection{
			Package: pkg,
			Version: 1,
			Shapes: []contractpeering.ContractEntry{
				{
					Kind:       "event-envelope",
					GoSymbol:   pkg + "." + name,
					Convention: conv,
				},
			},
		},
	}
	data, err := yaml.Marshal(m)
	if err != nil {
		t.Fatalf("marshal manifest: %v", err)
	}
	manifestPath := filepath.Join(heroDir, "peer-manifest.yaml")
	if err := os.WriteFile(manifestPath, data, 0o644); err != nil {
		t.Fatalf("write manifest: %v", err)
	}
	return manifestPath
}

// scannerFixture returns (originRoot, peerRoot) with origin
// registered against the peer and peer publishing a contract symbol.
func scannerFixture(t *testing.T) (originRoot, peerRoot, pkg, sym string) {
	t.Helper()
	root := t.TempDir()
	originRoot = filepath.Join(root, "client")
	peerRoot = filepath.Join(root, "app")
	setupWorkspace(t, originRoot, "11111111-1111-4111-8111-111111111111")
	setupWorkspace(t, peerRoot, "22222222-2222-4222-8222-222222222222")

	pkg = "contracts/events"
	sym = "Envelope"
	writePeerManifestWithContracts(t, peerRoot, "22222222-2222-4222-8222-222222222222", pkg, sym, "error-envelope")

	cfg, _ := config.Load(originRoot)
	cfg.Repos = map[string]string{"app": peerRoot}
	if err := cfg.Save(originRoot); err != nil {
		t.Fatalf("save cfg: %v", err)
	}
	return originRoot, peerRoot, pkg, sym
}

// TestScanContractImportsHit verifies a positive match: changed Go
// file in origin imports a contract symbol declared in a peer's
// manifest.
func TestScanContractImportsHit(t *testing.T) {
	originRoot, _, _, _ := scannerFixture(t)

	consumer := filepath.Join(originRoot, "api", "orders.go")
	if err := os.MkdirAll(filepath.Dir(consumer), 0o755); err != nil {
		t.Fatalf("mkdir: %v", err)
	}
	src := `package api

import (
	"fmt"
	"github.com/example/app/contracts/events"
)

func Render(e events.Envelope) string {
	return fmt.Sprintf("%v", e)
}
`
	if err := os.WriteFile(consumer, []byte(src), 0o644); err != nil {
		t.Fatalf("write consumer: %v", err)
	}

	hits, err := ScanContractImports(originRoot, ScanOptions{
		ChangedFiles: []string{"api/orders.go"},
	})
	if err != nil {
		t.Fatalf("scan: %v", err)
	}
	if len(hits) != 1 {
		t.Fatalf("expected 1 hit, got %d", len(hits))
	}
	h := hits[0]
	if h.PeerAlias != "app" {
		t.Errorf("alias: %q", h.PeerAlias)
	}
	if h.SymbolName != "Envelope" {
		t.Errorf("symbol: %q", h.SymbolName)
	}
	if h.SymbolPackage != "contracts/events" {
		t.Errorf("package: %q", h.SymbolPackage)
	}
	if h.Convention != "error-envelope" {
		t.Errorf("convention: %q", h.Convention)
	}
}

