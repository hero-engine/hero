// TestRenderContractImportSignal verifies the one-line output shape.
func TestRenderContractImportSignal(t *testing.T) {
	hits := []ContractImportHit{
		{
			File:              "api/orders.go",
			SymbolPackage:     "contracts/events",
			SymbolName:        "Envelope",
			FullSymbol:        "contracts/events.Envelope",
			PeerAlias:         "app",
			PeerID:            "9c1c2f3e-4a8b-4f9d-9a0e-7e1f0d8c3a55",
			Convention:        "error-envelope",
			LastChangedCommit: "4427cec",
		},
	}
	out := RenderContractImportSignal(hits)
	if out == "" {
		t.Fatal("expected non-empty signal")
	}
	checks := []string{
		"peer-contract-imports",
		"contracts/events.Envelope",
		"api/orders.go",
		"peer `app`",
		"9c1c2f3e",
		"error-envelope",
		"4427cec",
	}
	for _, s := range checks {
		if !strings.Contains(out, s) {
			t.Errorf("rendered signal missing %q:\n%s", s, out)
		}
	}
}

// TestRenderContractImportSignalEmpty: empty hits → empty signal.
func TestRenderContractImportSignalEmpty(t *testing.T) {
	if RenderContractImportSignal(nil) != "" {
		t.Error("empty hits should produce empty signal")
	}
}
